import {defineConfig, loadEnv} from 'vite';
import react from '@vitejs/plugin-react';
import {writeFileSync} from 'node:fs';
import {resolve} from 'node:path';

// src/services/api.js appends its own paths (/auth/login, /listings …) to
// VITE_API_BASE_URL. A base without the
// /api suffix therefore 404s on every call, and a trailing slash asks for
// /api//auth/login. Both look fine in the browser console until a user hits them, so
// reject the malformed value at build time. See the root `.env.example`.
function validateApiBase(apiBase, mode) {
  // Dev calls go through the /api proxy below, so nothing to check.
  if (mode !== 'production') return;

  if (!apiBase) {
    console.warn(
      '[infy_exchange] VITE_API_BASE_URL is unset; the build will call "/api" on the ' +
        'frontend origin. For Cloudflare Pages with a separate Cloud Run API, set it ' +
        'to the service URL ending in /api.'
    );
    return;
  }
  if (apiBase.endsWith('/')) {
    throw new Error(
      `[infy_exchange] VITE_API_BASE_URL "${apiBase}" must not end with "/" ` +
        '(api.js appends its own leading slash).'
    );
  }
  if (!apiBase.endsWith('/api')) {
    throw new Error(
      `[infy_exchange] VITE_API_BASE_URL "${apiBase}" must end with "/api" — ` +
        'the API is mounted under /api.'
    );
  }
}

// Flip to true once the report-only burn-in shows no violations in the browser
// console (docs/security/SECURITY_RUNBOOK.md §5.3). Report-only is logged and not
// enforced, so a wrong rule cannot take the deployed site down.
const CSP_ENFORCE = false;

// The SPA is served from a different origin than the API, so API response headers
// cannot govern this document — and this document is the one holding
// infy_token in localStorage. HTML-facing controls therefore have to ship with the
// bundle (runbook §5.3). Generated instead of hand-written so the CSP can never
// drift from the origin the bundle actually calls: one source of truth, no
// placeholder left behind in dist/ to silently break the app when CSP is enforced.
function buildSpaHeaders(apiBase, googleSignIn) {
  const apiOrigin = /^https?:\/\//.test(apiBase) ? new URL(apiBase).origin : null;

  // Google Sign-In loads one script, draws its button in an iframe and calls back to
  // accounts.google.com. These sources are allowed only when a client ID is configured,
  // so a build without Google keeps the tighter policy.
  const GSI = 'https://accounts.google.com/gsi/';

  const csp = [
    "default-src 'self'",
    `script-src 'self'${googleSignIn ? ` ${GSI}client` : ''}`,
    // No 'unsafe-inline': React assigns style props through the CSSOM, which CSP
    // does not gate, and `vite build` emits an external stylesheet, no <style>.
    `style-src 'self' https://fonts.googleapis.com${googleSignIn ? ` ${GSI}style` : ''}`,
    "font-src 'self' https://fonts.gstatic.com",
    // data: = Vite's inlined assets; Cloudinary = every listing image (secure_url).
    "img-src 'self' data: https://res.cloudinary.com",
    // A relative base ('/api') is same-origin, so 'self' already covers it.
    ['connect-src', "'self'", ...(apiOrigin ? [apiOrigin] : []), ...(googleSignIn ? [GSI] : [])].join(' '),
    ...(googleSignIn ? [`frame-src ${GSI}`] : []),
    "frame-ancestors 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "object-src 'none'",
    // Only while the API is https: this directive would rewrite an http://<ip> base
    // and break the pre-TLS smoke deploy.
    ...(apiOrigin?.startsWith('https://') ? ['upgrade-insecure-requests'] : []),
  ].join('; ');

  return [
    '# Generated by the infyexchange:spa-headers plugin in vite.config.js — do not edit.',
    '# Read from the Cloudflare Pages build output directory.',
    '',
    '/*',
    '  X-Content-Type-Options: nosniff',
    '  X-Frame-Options: DENY',
    '  Referrer-Policy: strict-origin-when-cross-origin',
    '  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=()',
    `  ${CSP_ENFORCE ? 'Content-Security-Policy' : 'Content-Security-Policy-Report-Only'}: ${csp}`,
    '# Enable only after HTTPS is confirmed and the CSP burn-in is clean, then ramp',
    '# the same way as the API origin (SECURITY_RUNBOOK §5.4).',
    '#   Strict-Transport-Security: max-age=31536000',
    '',
    '# Hashed filenames are safe to pin forever; index.html must not be cached, or a',
    '# returning visitor asks for asset hashes the new deploy no longer has.',
    '/assets/*',
    '  Cache-Control: public, max-age=31536000, immutable',
    '  X-Content-Type-Options: nosniff',
    '',
    '/index.html',
    '  Cache-Control: no-cache',
    '',
  ].join('\n');
}

function spaHeaders(apiBase, googleSignIn) {
  let root = process.cwd();
  let outDir = 'dist';

  return {
    name: 'infyexchange:spa-headers',
    apply: 'build',
    configResolved(config) {
      root = config.root;
      outDir = config.build.outDir;
    },
    writeBundle() {
      writeFileSync(resolve(root, outDir, '_headers'), buildSpaHeaders(apiBase, googleSignIn), 'utf8');
    },
  };
}

export default defineConfig(({mode}) => {
  // Dashboard-supplied values arrive via process.env and take precedence over files.
  const apiBase =
    loadEnv(mode, process.cwd()).VITE_API_BASE_URL ?? process.env.VITE_API_BASE_URL ?? '';
  validateApiBase(apiBase, mode);
  const googleSignIn = Boolean(
    loadEnv(mode, process.cwd()).VITE_GOOGLE_CLIENT_ID ?? process.env.VITE_GOOGLE_CLIENT_ID
  );

  return {
    plugins: [react(), spaHeaders(apiBase, googleSignIn)],
    server: { proxy: { '/api': 'http://127.0.0.1:8000' } },
  };
});
